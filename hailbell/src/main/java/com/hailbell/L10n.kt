    val language: String by lazy {
        val code = Locale.getDefault().language.lowercase()
        if (table.containsKey(code)) code else "en"
    }

    fun text(key: String, vars: Map<String, String> = emptyMap()): String = text(key, vars, language)

    /** [text] in a given language, for tests and for words that must match a known language. */
    fun text(key: String, vars: Map<String, String>, lang: String): String {
        var s = table[lang]?.get(key) ?: table["en"]?.get(key) ?: key
        for ((k, v) in vars) s = s.replace("{$k}", v)
        return s
    }

